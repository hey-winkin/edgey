import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import ts from "typescript";

const output = execFileSync("supabase", ["gen", "types", "--schema", "public"], {
  encoding: "utf8",
  stdio: ["ignore", "pipe", "inherit"],
  maxBuffer: 10 * 1024 * 1024,
});
const source = ts.createSourceFile("database.generated.ts", output, ts.ScriptTarget.Latest, true);
if (source.parseDiagnostics.length || source.statements.length === 0) {
  throw new Error("Supabase did not produce valid TypeScript.");
}
const generated = ts.createPrinter({ newLine: ts.NewLineKind.LineFeed }).printFile(source);
writeFileSync(
  new URL("../src/lib/supabase/database.generated.ts", import.meta.url),
  "// Generated by pnpm db:types. Do not edit.\n" + generated,
);
